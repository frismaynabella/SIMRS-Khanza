    public void setNoRm(String norawat){
        TNoRw.setText(norawat);
        TNoRM.setText("");
        TPasien.setText("");
        KdDokter.setText("");
        NmDokter.setText("");
        NoSurat.setText("");
        Kesimpulan.setText("Tidak Didapatkan Tanda/Gejala Gangguan Jiwa");
        Keperluan.setText("");
        TglPeriksa.setDate(new Date());
        TglSurat.setDate(new Date());
        try {
            ps=koneksi.prepareStatement(
                "select reg_periksa.no_rkm_medis,pasien.nm_pasien,reg_periksa.kd_dokter,dokter.nm_dokter,reg_periksa.tgl_registrasi "+
                "from reg_periksa inner join pasien on reg_periksa.no_rkm_medis=pasien.no_rkm_medis "+
                "inner join dokter on reg_periksa.kd_dokter=dokter.kd_dokter where reg_periksa.no_rawat=?");
            try {
                ps.setString(1,norawat);
                rs=ps.executeQuery();
                if(rs.next()){
                    TNoRM.setText(rs.getString("no_rkm_medis"));
                    TPasien.setText(rs.getString("nm_pasien"));
                    KdDokter.setText(rs.getString("kd_dokter"));
                    NmDokter.setText(rs.getString("nm_dokter"));
                    TglPeriksa.setDate(rs.getDate("tgl_registrasi"));
                }
            } catch (Exception e) {
                System.out.println("Notif : "+e);
            } finally{
                if(rs!=null){
                    rs.close();
                }
                if(ps!=null){
                    ps.close();
                }
            }
        } catch (Exception e) {
            System.out.println("Notif : "+e);
        }
    }

    // contoh: "sepuluh, bulan agustus, tahun dua ribu dua puluh enam"
    private String tanggalTerbilang(Date tgl){
        Calendar c=Calendar.getInstance();
        c.setTime(tgl);
        return (Valid.terbilang(c.get(Calendar.DAY_OF_MONTH))+", bulan "+namabulan[c.get(Calendar.MONTH)].toLowerCase()+
                ", tahun "+Valid.terbilang(c.get(Calendar.YEAR))).replaceAll("\\s+"," ").replace(" ,",",").trim();
    }

    // contoh: "10 Agustus 2026"
    private String tanggalPanjang(Date tgl){
        Calendar c=Calendar.getInstance();
        c.setTime(tgl);
        return c.get(Calendar.DAY_OF_MONTH)+" "+namabulan[c.get(Calendar.MONTH)]+" "+c.get(Calendar.YEAR);
    }
